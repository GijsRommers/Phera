pub(crate) fn name(id: i64) -> Option<&'static str> {
    let offset = (id as i32).checked_sub(Id::Lnumber as i32)?;
    let (name, _) = CONSTANTS.get(usize::try_from(offset).ok()?)?;
    Some(name)
}
