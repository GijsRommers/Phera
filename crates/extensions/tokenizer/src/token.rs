//! Convert Phera lexer kinds to PHP's numbered tokens or ASCII punctuation.
//!
//! `token_get_all("<?php $x += 1;")` includes a numbered `T_PLUS_EQUAL` but
//! represents the final semicolon as the one-character string `";"`.

use phera_lexer::TokenKind;

use crate::ids::Id;

pub(crate) fn id(kind: TokenKind, text: &[u8]) -> i64 {
    use TokenKind::*;
    let id = match kind {
        InlineHtml => Id::InlineHtml,
        OpenTag => Id::OpenTag,
        OpenTagWithEcho => Id::OpenTagWithEcho,
        CloseTag => Id::CloseTag,
        Identifier | True | False | Null => Id::String,
        QualifiedName => Id::NameQualified,
        FullyQualifiedName => Id::NameFullyQualified,
        RelativeName => Id::NameRelative,
        Variable => Id::Variable,
        Integer => Id::Lnumber,
        Float => Id::Dnumber,
        String => Id::ConstantEncapsedString,
        StringPart => Id::EncapsedAndWhitespace,
        StartHeredoc => Id::StartHeredoc,
        EndHeredoc => Id::EndHeredoc,
        CurlyOpen => Id::CurlyOpen,
        DollarCurlyOpen => Id::DollarOpenCurlyBraces,
        StringVarname => Id::StringVarname,
        NumString => Id::NumString,
        Abstract => Id::Abstract,
        And => Id::LogicalAnd,
        Array => Id::Array,
        As => Id::As,
        Break => Id::Break,
        Callable => Id::Callable,
        Case => Id::Case,
        Catch => Id::Catch,
        Class => Id::Class,
        Clone => Id::Clone,
        Const => Id::Const,
        Continue => Id::Continue,
        Declare => Id::Declare,
        Default => Id::Default,
        Do => Id::Do,
        Echo => Id::Echo,
        Else => Id::Else,
        ElseIf => Id::Elseif,
        Empty => Id::Empty,
        EndDeclare => Id::Enddeclare,
        EndFor => Id::Endfor,
        EndForeach => Id::Endforeach,
        EndIf => Id::Endif,
        EndSwitch => Id::Endswitch,
        EndWhile => Id::Endwhile,
        Eval => Id::Eval,
        Exit => Id::Exit,
        Extends => Id::Extends,
        Final => Id::Final,
        Finally => Id::Finally,
        Fn => Id::Fn,
        For => Id::For,
        Foreach => Id::Foreach,
        Function => Id::Function,
        Global => Id::Global,
        Goto => Id::Goto,
        If => Id::If,
        Implements => Id::Implements,
        Include => Id::Include,
        IncludeOnce => Id::IncludeOnce,
        InstanceOf => Id::Instanceof,
        InsteadOf => Id::Insteadof,
        Interface => Id::Interface,
        Isset => Id::Isset,
        List => Id::List,
        Match => Id::Match,
        Namespace => Id::Namespace,
        New => Id::New,
        Or => Id::LogicalOr,
        Print => Id::Print,
        Private => Id::Private,
        Protected => Id::Protected,
        Public => Id::Public,
        Readonly => Id::Readonly,
        Require => Id::Require,
        RequireOnce => Id::RequireOnce,
        Return => Id::Return,
        Static => Id::Static,
        Switch => Id::Switch,
        Throw => Id::Throw,
        Trait => Id::Trait,
        Try => Id::Try,
        Unset => Id::Unset,
        Use => Id::Use,
        Var => Id::Var,
        While => Id::While,
        Xor => Id::LogicalXor,
        Yield => Id::Yield,
        YieldFrom => Id::YieldFrom,
        Enum => Id::Enum,
        HaltCompiler => Id::HaltCompiler,
        PublicSet => Id::PublicSet,
        ProtectedSet => Id::ProtectedSet,
        PrivateSet => Id::PrivateSet,
        MagicDir => Id::Dir,
        MagicFile => Id::File,
        MagicLine => Id::Line,
        MagicClass => Id::ClassC,
        MagicFunction => Id::FuncC,
        MagicMethod => Id::MethodC,
        MagicNamespace => Id::NsC,
        MagicTrait => Id::TraitC,
        MagicProperty => Id::PropertyC,
        IntCast => Id::IntCast,
        FloatCast => Id::DoubleCast,
        StringCast => Id::StringCast,
        ArrayCast => Id::ArrayCast,
        ObjectCast => Id::ObjectCast,
        BoolCast => Id::BoolCast,
        UnsetCast => Id::UnsetCast,
        VoidCast => Id::VoidCast,
        Power => Id::Pow,
        Increment => Id::Inc,
        Decrement => Id::Dec,
        PlusAssign => Id::PlusEqual,
        MinusAssign => Id::MinusEqual,
        StarAssign => Id::MulEqual,
        SlashAssign => Id::DivEqual,
        PercentAssign => Id::ModEqual,
        PowerAssign => Id::PowEqual,
        DotAssign => Id::ConcatEqual,
        NullCoalesceAssign => Id::CoalesceEqual,
        AmpersandAssign => Id::AndEqual,
        PipeAssign => Id::OrEqual,
        CaretAssign => Id::XorEqual,
        ShiftLeftAssign => Id::SlEqual,
        ShiftRightAssign => Id::SrEqual,
        Equal => Id::IsEqual,
        Identical => Id::IsIdentical,
        NotEqual => Id::IsNotEqual,
        NotIdentical => Id::IsNotIdentical,
        LessEqual => Id::IsSmallerOrEqual,
        GreaterEqual => Id::IsGreaterOrEqual,
        Spaceship => Id::Spaceship,
        LogicalAnd => Id::BooleanAnd,
        LogicalOr => Id::BooleanOr,
        Ampersand => Id::AmpersandNotFollowedByVarOrVararg,
        AmpersandBeforeVariable => Id::AmpersandFollowedByVarOrVararg,
        ShiftLeft => Id::Sl,
        ShiftRight => Id::Sr,
        Arrow => Id::ObjectOperator,
        NullsafeArrow => Id::NullsafeObjectOperator,
        DoubleColon => Id::DoubleColon,
        FatArrow => Id::DoubleArrow,
        NullCoalesce => Id::Coalesce,
        PipeForward => Id::Pipe,
        Backslash => Id::NsSeparator,
        Ellipsis => Id::Ellipsis,
        AttributeStart => Id::Attribute,
        Whitespace => Id::Whitespace,
        Comment => Id::Comment,
        DocComment => Id::DocComment,
        BadCharacter => Id::BadCharacter,
        DoubleQuote => return i64::from(b'"'),
        Plus | Minus | Star | Slash | Percent | Dot | Assign | Less | Greater | Not | Pipe
        | Caret | Tilde | Question | At | Dollar | LeftParen | RightParen | LeftBrace
        | RightBrace | LeftBracket | RightBracket | Semicolon | Comma | Colon | Backquote
        | OffsetAmpersand => return i64::from(text[0]),
        Eof => unreachable!("EOF is not a PHP token"),
    };
    id as i64
}

pub(crate) fn ignorable(id: i64) -> bool {
    [Id::Whitespace, Id::Comment, Id::DocComment, Id::OpenTag]
        .iter()
        .any(|kind| *kind as i64 == id)
}
