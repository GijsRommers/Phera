//! The `Redis` class, with the 287 methods of phpredis 6.3.0, and
//! `RedisException`. RedisCluster, RedisSentinel and RedisArray are not
//! registered.
//!
//! ```php
//! $redis = new Redis();
//! $redis->connect('127.0.0.1');
//! $redis->set('greeting', 'hello');
//! ```
//!
//! Each module here holds one family's signatures, as phpredis declares them,
//! with the code that implements them named in its first line.

