"""Generate the complete method report from the checked-in real-PHP reflection inventory."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
methods = json.loads((root / 'tools/phpredis-6.3.0.json').read_text())['methods']
not_done = set('''failover getTransferredBytes clearTransferredBytes migrate
vadd vsim vcard vdim vinfo vismember vemb vrandmember vrange vrem vsetattr vgetattr vlinks'''.lower().split())
done = set('''__destruct clearLastError close echo getAuth getDBNum getHost getLastError
getMode getPersistentID getPort getReadTimeout getTimeout isConnected serverName serverVersion
append decr decrBy incr incrBy incrByFloat strlen getRange setRange getBit setBit
hDel hExists hIncrBy hIncrByFloat hKeys hLen hStrLen lLen scard ttl pttl persist
expiretime pexpiretime type rename renameNx dump del unlink exists touch
getWithMeta hGetWithMeta flushDB'''.lower().split())
notes = {
    '__construct': 'Lazy options work; SSL contexts, retry and backoff options are incomplete.',
    'connect': 'TCP/Unix and rustls paths; retry interval and SSL context parity incomplete.',
    'pconnect': 'Pooled TCP/Unix, persistent ID retained; same transport limitations as connect.',
    'open': 'Deprecated connect alias; same transport limitations.',
    'popen': 'Deprecated pconnect alias; same transport limitations.',
    'setoption': 'Requested flags, NONE/JSON and no compression; other constants unsupported.',
    'getoption': 'Returns supported flags; retry/backoff/keepalive options unsupported.',
    'gettransferredbytes': 'Wire byte counters not implemented.',
    'cleartransferredbytes': 'Wire byte counters not implemented.',
    'failover': 'Topology-changing command not implemented.',
    'migrate': 'Cross-server key migration not implemented.',
    'flushall': 'Command encoder present; never executed by this task or its tests.',
    'flushdb': 'Default, SYNC and ASYNC compared only on task-owned database 12.',
    'expiremember': 'KeyDB command encoder; Redis 8.4 oracle returns unknown command.',
    'expirememberat': 'KeyDB command encoder; Redis 8.4 oracle returns unknown command.',
}
for method in ['_compress', '_uncompress', '_serialize', '_unserialize', '_pack', '_unpack']:
    notes[method] = 'NONE/JSON only; PHP serialization and compression codecs unavailable.'
for method in ['subscribe', 'psubscribe', 'ssubscribe', 'unsubscribe', 'punsubscribe', 'sunsubscribe']:
    notes[method] = 'Dedicated socket and callback/unsubscribe parity checked; reconnect/error cases incomplete.'
for method in ['multi', 'exec', 'discard', 'pipeline', 'watch', 'unwatch']:
    notes[method] = 'Pinning, replies, abort and cleanup implemented; exhaustive cross-family options remain.'
for method in ['save', 'bgsave', 'bgrewriteaof', 'replicaof', 'slaveof', 'swapdb']:
    notes[method] = 'Command encoder present; state-changing success paths not exercised.'

rows = []
counts = {'DONE': 0, 'PARTIAL': 0, 'NOT DONE': 0}
for method in methods:
    name = method.lower()
    status = 'NOT DONE' if name in not_done else 'DONE' if name in done else 'PARTIAL'
    counts[status] += 1
    note = notes.get(name, 'Vector-set method not implemented.' if name.startswith('v') else
                     'Implemented; complete option/type/error cross-product is not yet verified.'
                     if status == 'PARTIAL' else 'Implemented and covered by direct oracle comparisons.')
    rows.append(f'| `{method}` | {status} | {note} |')
text = '''# Redis method status

Generated by `python3 crates/extensions/redis/tools/generate-status.py` from
[`tools/phpredis-6.3.0.json`](tools/phpredis-6.3.0.json), reflected from phpredis 6.3.0.
All 287 reflected Redis methods are listed exactly once. No global functions are added.
`RedisException` is registered with its RuntimeException ancestry and code/message properties.
RedisCluster, RedisSentinel and RedisArray are out of scope and not registered.

DONE identifies implemented, directly compared behavior without a known method-specific gap.
PARTIAL means implemented behavior with known gaps or insufficient coverage for the requested
all-forms compatibility gate. Registration alone is never counted as implementation.
NOT DONE methods have their reflected signatures but throw an explicit not-implemented exception.
The overall extension remains PARTIAL. Serializer/compression limitations apply to every family.
`MEMORY` and `BITFIELD` have no methods in this oracle inventory; use `rawCommand`.

'''
text += ', '.join(f'{count} {status}' for status, count in counts.items()) + '.\n\n'
text += '| Method | Status | Evidence or remaining work |\n| --- | --- | --- |\n'
text += '\n'.join(rows) + '\n'
(root / 'METHODS.md').write_text(text)
print(counts)
