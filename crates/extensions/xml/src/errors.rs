pub fn error_string(_: &mut dyn Context, arguments: &[Value]) -> NativeResult {
    let index = args::int(arguments, 0).and_then(|code| usize::try_from(code).ok());
    let message = index
        .and_then(|index| ERRORS.get(index))
        .copied()
        .unwrap_or("Unknown");
    Ok(Value::from(message))
}
