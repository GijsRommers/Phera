//! Setting `CURLOPT_COOKIEFILE` to an empty string enables response cookies.

use std::{
    cell::RefCell,
    rc::Rc,
    time::{Duration, UNIX_EPOCH},
};

use cookie_store::{Cookie, CookieDomain, CookieExpiration, CookieStore, RawCookie};
use phera_extension_api::{Context, NativeResult, PhpArray, Value};
use url::Url;

pub(crate) type CookieJar = Rc<RefCell<Cookies>>;

#[derive(Default)]
pub(crate) struct Cookies {
    pub(crate) enabled: bool,
    store: CookieStore,
}

impl Cookies {
    pub(crate) fn parse(&mut self, value: &str, url: &Url) {
        let Ok(cookie) = RawCookie::parse(value) else {
            return;
        };
        if let Some(domain) = cookie.domain()
            && psl::suffix_str(domain) == Some(domain)
            && url.host_str() != Some(domain)
        {
            return;
        }
        let _ = self.store.insert_raw(&cookie, url);
    }

    pub(crate) fn header(&self, url: &Url) -> String {
        let mut cookies = self.store.matches(url);
        cookies.sort_by_key(|cookie| std::cmp::Reverse(cookie.path.as_ref().len()));
        cookies
            .into_iter()
            .map(|cookie| format!("{}={}", cookie.name(), cookie.value()))
            .collect::<Vec<_>>()
            .join("; ")
    }

    fn lines(&self) -> impl Iterator<Item = String> + '_ {
        self.store.iter_unexpired().filter_map(netscape_line)
    }
}

pub(crate) fn list(jar: &CookieJar) -> NativeResult {
    let mut result = PhpArray::new();
    for line in jar.borrow().lines() {
        result.push(Value::from(line))?;
    }
    Ok(Value::from(result))
}

fn netscape_line(cookie: &Cookie<'_>) -> Option<String> {
    let domain = cookie.domain.as_cow()?;
    let includes_subdomains = matches!(cookie.domain, CookieDomain::Suffix(_));
    let expiry = match cookie.expires {
        CookieExpiration::AtUtc(time) => time.unix_timestamp(),
        CookieExpiration::SessionEnd => 0,
    };
    let prefix = if cookie.http_only() == Some(true) {
        "#HttpOnly_"
    } else {
        ""
    };
    let dot = if includes_subdomains { "." } else { "" };
    Some(format!(
        "{prefix}{dot}{domain}\t{}\t{}\t{}\t{expiry}\t{}\t{}",
        boolean(includes_subdomains),
        cookie.path.as_ref(),
        boolean(cookie.secure() == Some(true)),
        cookie.name(),
        cookie.value(),
    ))
}

fn boolean(flag: bool) -> &'static str {
    if flag { "TRUE" } else { "FALSE" }
}

fn import(jar: &mut Cookies, line: &str, new_session: bool) {
    if let Some(cookie) = line.strip_prefix("Set-Cookie:").map(str::trim) {
        let Ok(raw) = RawCookie::parse(cookie) else {
            return;
        };
        let Some(domain) = raw.domain() else { return };
        if let Ok(url) = Url::parse(&format!("https://{domain}/")) {
            jar.parse(cookie, &url);
        }
        return;
    }
    let (http_only, line) = line
        .strip_prefix("#HttpOnly_")
        .map_or((false, line), |line| (true, line));
    if line.starts_with('#') {
        return;
    }
    let fields: Vec<_> = line.splitn(7, '\t').collect();
    let [domain, include, path, secure, expires, name, value] = fields.as_slice() else {
        return;
    };
    let Ok(expires) = expires.parse::<u64>() else {
        return;
    };
    if new_session && expires == 0 {
        return;
    }
    let domain = domain.trim_start_matches('.');
    let Ok(url) = Url::parse(&format!("https://{domain}/")) else {
        return;
    };
    let mut cookie = format!("{name}={value}; Path={path}");
    if *include == "TRUE" {
        cookie.push_str(&format!("; Domain={domain}"));
    }
    if *secure == "TRUE" {
        cookie.push_str("; Secure");
    }
    if http_only {
        cookie.push_str("; HttpOnly");
    }
    if expires != 0 {
        let Some(time) = UNIX_EPOCH.checked_add(Duration::from_secs(expires)) else {
            return;
        };
        if expires > 253_402_300_799 {
            return;
        }
        cookie.push_str(&format!("; Expires={}", httpdate::fmt_http_date(time)));
    }
    jar.parse(&cookie, &url);
}

pub(crate) async fn load(
    context: &mut dyn Context,
    jar: &CookieJar,
    files: &[Vec<u8>],
    new_session: bool,
) {
    for file in files
        .iter()
        .filter(|file| !file.is_empty() && file.as_slice() != b"-")
    {
        let path = crate::options::path(context, file);
        if let Ok(path) = path
            && let Ok(text) = tokio::fs::read_to_string(path).await
        {
            let mut jar = jar.borrow_mut();
            for line in text.lines() {
                import(&mut jar, line, new_session);
            }
        }
    }
}

pub(crate) async fn save(context: &mut dyn Context, jar: &CookieJar, file: &[u8]) {
    let mut text = "# Netscape HTTP Cookie File\n# Generated by Phera.\n\n".to_owned();
    for line in jar.borrow().lines() {
        text.push_str(&line);
        text.push('\n');
    }
    if file == b"-" {
        context.write(text.as_bytes());
    } else if let Ok(path) = crate::options::path(context, file)
        && let Err(error) = tokio::fs::write(path, text).await
    {
        context.warning(format!("cURL could not save cookies: {error}"));
    }
}

pub(crate) async fn command(
    context: &mut dyn Context,
    jar: &CookieJar,
    output: Option<&[u8]>,
    files: &[Vec<u8>],
    new_session: bool,
    command: &[u8],
) {
    jar.borrow_mut().enabled = true;
    match command {
        b"ALL" => jar.borrow_mut().store.clear(),
        b"SESS" => {
            let mut jar = jar.borrow_mut();
            let rebuilt = CookieStore::from_cookies(
                jar.store
                    .iter_unexpired()
                    .filter(|cookie| cookie.is_persistent())
                    .cloned()
                    .map(Ok::<_, std::convert::Infallible>),
                false,
            );
            let Ok(store) = rebuilt;
            jar.store = store;
        }
        b"FLUSH" => {
            if let Some(file) = output {
                save(context, jar, file).await;
            }
        }
        b"RELOAD" => load(context, jar, files, new_session).await,
        _ => {
            if let Ok(line) = std::str::from_utf8(command) {
                import(&mut jar.borrow_mut(), line, false);
            }
        }
    }
}
