//! Socket families, options, and errors use the platform's numeric constants.

use nix::libc;
use phera_extension_api::Registry;

pub(crate) fn register(registry: &mut Registry) {
    for (name, number) in COMMON {
        registry.constant(name, i64::from(*number));
    }
    #[cfg(target_os = "linux")]
    for (name, number) in LINUX {
        registry.constant(name, i64::from(*number));
    }
    #[cfg(target_vendor = "apple")]
    for (name, number) in APPLE {
        registry.constant(name, i64::from(*number));
    }
}

