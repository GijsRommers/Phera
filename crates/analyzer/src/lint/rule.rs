//! Rules recognize syntax such as `$a = $a` and describe their findings with stable names.

use super::{Context, traversal::Node};
use std::fmt::Write;

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Group {
    Syntax,
    Suspicious,
    Unused,
    Modernize,
    Style,
    Naming,
    Complexity,
}

impl Group {
    pub const ALL: [Self; 7] = [
        Self::Syntax,
        Self::Suspicious,
        Self::Unused,
        Self::Modernize,
        Self::Style,
        Self::Naming,
        Self::Complexity,
    ];

    pub const fn name(self) -> &'static str {
        match self {
            Self::Syntax => "syntax",
            Self::Suspicious => "suspicious",
            Self::Unused => "unused",
            Self::Modernize => "modernize",
            Self::Style => "style",
            Self::Naming => "naming",
            Self::Complexity => "complexity",
        }
    }

    pub fn parse(name: &str) -> Result<Self, String> {
        Self::ALL
            .into_iter()
            .find(|group| group.name() == name)
            .ok_or_else(|| format!("Unknown lint group: {name}"))
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Visit {
    File,
    Block,
    Statement,
    Expression,
    Namespace,
}

pub(super) type Check = fn(&mut Context<'_>, Node<'_>);

#[derive(Clone, Copy)]
pub(super) enum DefaultStatus {
    Enabled,
    OptIn,
}

pub struct Rule {
    pub name: &'static str,
    pub group: Group,
    pub description: &'static str,
    pub(super) default: DefaultStatus,
    pub(super) bad: &'static str,
    pub(super) good: &'static str,
    pub(super) fix: &'static str,
    pub(super) visit: Visit,
    pub(super) check: Option<Check>,
}

impl Rule {
    pub fn documentation(&self) -> String {
        let status = match self.default {
            DefaultStatus::Enabled => "Enabled by default.",
            DefaultStatus::OptIn => "Opt-in.",
        };
        let mut output = format!(
            "## `{}`\n\nGroup: `{}`. {} {}\n\n{}\n\n",
            self.name,
            self.group.name(),
            status,
            self.fix,
            self.description,
        );
        let _ = write!(
            output,
            "Before\n\n```php\n{}\n```\n\nAfter\n\n```php\n{}\n```\n",
            self.bad, self.good
        );
        output
    }
}

pub(super) const SYNTAX: Rule = Rule {
    name: "syntax-error",
    group: Group::Syntax,
    description: "Report the first source error at the selected PHP language level.",
    default: DefaultStatus::Enabled,
    bad: "<?php\necho ;",
    good: "<?php\necho 'Hello';",
    fix: "",
    visit: Visit::File,
    check: None,
};

pub(super) const UNUSED_SUPPRESSION: Rule = Rule {
    name: "unused-suppression",
    group: Group::Syntax,
    description: "Remove a suppression that does not hide a lint finding.",
    default: DefaultStatus::Enabled,
    bad: "<?php\n// phera-ignore unused-suppression obsolete waiver\necho 1;",
    good: "<?php\necho 1;",
    fix: "",
    visit: Visit::File,
    check: None,
};

pub fn rules() -> impl Iterator<Item = &'static Rule> {
    [&SYNTAX, &UNUSED_SUPPRESSION]
        .into_iter()
        .chain(super::suspicious::RULES)
        .chain(super::imports::RULES)
        .chain(super::locals::RULES)
        .chain(super::members::RULES)
}

pub fn find(name: &str) -> Option<&'static Rule> {
    rules().find(|rule| rule.name == name)
}

pub fn catalog() -> String {
    let mut output =
        String::from("# Phera lint rules\n\nGenerated by `phera lint --list-rules`.\n\n");
    for group in Group::ALL {
        for rule in rules().filter(|rule| rule.group == group) {
            let _ = writeln!(
                output,
                "- `{}` (`{}`) — {}",
                rule.name,
                group.name(),
                rule.description
            );
        }
    }
    for group in Group::ALL {
        for rule in rules().filter(|rule| rule.group == group) {
            output.push('\n');
            output.push_str(&rule.documentation());
        }
    }
    output
}
