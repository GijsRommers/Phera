//! PHPStan's generated baseline groups a message, an identifier and a count
//! under a path. The count permits two existing errors to stay suppressed
//! while a third occurrence of the same error is still reported.

use crate::diagnostic::Diagnostic;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

mod scalars;

#[derive(Default)]
struct Entry {
    message: Option<String>,
    identifier: Option<String>,
    path: Option<PathBuf>,
    count: Option<usize>,
}

pub(super) fn filter(
    file: &Path,
    source: &str,
    diagnostics: &mut Vec<Diagnostic>,
) -> Result<(), String> {
    let parent = file.parent().unwrap_or_else(|| Path::new(""));
    let mut entries: BTreeMap<PathBuf, Vec<Entry>> = BTreeMap::new();
    for mut entry in parse(file, source)? {
        if let Some(path) = entry.path.take()
            && let Ok(path) = parent.join(path).canonicalize()
        {
            entries.entry(path).or_default().push(entry);
        }
    }
    let mut last_file = String::new();
    let mut filename = None;
    diagnostics.retain(|diagnostic| {
        if last_file != diagnostic.file {
            last_file.clone_from(&diagnostic.file);
            filename = Path::new(&last_file).canonicalize().ok();
        }
        let Some(rules) = filename.as_ref().and_then(|name| entries.get_mut(name)) else {
            return true;
        };
        for rule in rules {
            let Some(count) = rule.count.as_mut() else {
                continue;
            };
            let candidate_id = canonical_identifier(&diagnostic.identifier);
            if *count > 0
                && rule
                    .identifier
                    .as_deref()
                    .is_none_or(|name| canonical_identifier(name) == candidate_id)
                && rule
                    .message
                    .as_deref()
                    .is_some_and(|message| matches_message(diagnostic, message))
            {
                *count -= 1;
                return false;
            }
        }
        true
    });
    Ok(())
}

fn parse(file: &Path, source: &str) -> Result<Vec<Entry>, String> {
    let mut lines = source
        .lines()
        .enumerate()
        .map(|(line, text)| (line + 1, text.trim()))
        .filter(|(_, text)| !text.is_empty() && !text.starts_with('#'));
    let error = |line, message| format!("{}:{line}: {message}", file.display());
    if !matches!(lines.next(), Some((_, "parameters:"))) {
        return Err(error(1, "expected parameters in the PHPStan baseline"));
    }
    match lines.next() {
        Some((_, "ignoreErrors: []")) if lines.next().is_none() => return Ok(Vec::new()),
        Some((_, "ignoreErrors:")) => {}
        Some((line, _)) => {
            return Err(error(line, "expected ignoreErrors in the PHPStan baseline"));
        }
        None => return Err(error(2, "expected ignoreErrors in the PHPStan baseline")),
    }
    let mut entries = Vec::new();
    let mut current = None::<(usize, Entry)>;
    for (line, text) in lines {
        if text == "-" {
            finish(&mut entries, current.take())
                .map_err(|line| error(line, "baseline entry needs message, count and path"))?;
            current = Some((line, Entry::default()));
            continue;
        }
        let Some((_, entry)) = &mut current else {
            return Err(error(line, "expected a PHPStan baseline entry"));
        };
        let Some((key, value)) = text.split_once(':') else {
            return Err(error(line, "expected a baseline entry key and value"));
        };
        let value = scalars::string(value.trim())
            .ok_or_else(|| error(line, "unsupported baseline value"))?;
        match key {
            "identifier" if entry.identifier.is_none() => entry.identifier = Some(value),
            "count" if entry.count.is_none() => {
                entry.count = value.parse().ok().filter(|count| *count > 0);
                if entry.count.is_none() {
                    return Err(error(line, "expected a positive baseline count"));
                }
            }
            "path" if entry.path.is_none() => entry.path = Some(value.into()),
            "rawMessage" if entry.message.is_none() => entry.message = Some(value),
            "message" if entry.message.is_none() => {
                entry.message = Some(scalars::literal_pattern(&value).ok_or_else(|| {
                    error(line, "expected an anchored message generated by PHPStan")
                })?);
            }
            _ => return Err(error(line, "unsupported or repeated baseline entry key")),
        }
    }
    finish(&mut entries, current)
        .map_err(|line| error(line, "baseline entry needs message, count and path"))?;
    Ok(entries)
}

fn finish(entries: &mut Vec<Entry>, pending: Option<(usize, Entry)>) -> Result<(), usize> {
    if let Some((line, entry)) = pending {
        if entry.message.is_none() || entry.path.is_none() || entry.count.is_none() {
            return Err(line);
        }
        entries.push(entry);
    }
    Ok(())
}

fn canonical_identifier(identifier: &str) -> &str {
    match identifier {
        "new.classNotFound" | "interface.notFound" | "trait.notFound" => "class.notFound",
        "staticMethod.notFound" => "method.notFound",
        other => other,
    }
}

fn matches_message(diagnostic: &Diagnostic, message: &str) -> bool {
    let actual = diagnostic
        .message
        .split_once(" The type was narrowed on line ")
        .map_or(diagnostic.message.as_str(), |(actual, _)| actual);
    if actual == message {
        return true;
    }
    match canonical_identifier(&diagnostic.identifier) {
        "class.notFound" => {
            missing_class(actual).is_some_and(|class| Some(class) == missing_class(message))
        }
        "return.type" => return_contract(actual)
            .is_some_and(|contract| Some(contract) == return_contract(message)),
        _ => false,
    }
}

fn missing_class(message: &str) -> Option<&str> {
    message
        .strip_prefix("Class ")
        .or_else(|| message.strip_prefix("Instantiated class "))
        .or_else(|| message.strip_prefix("Interface "))
        .or_else(|| message.strip_prefix("Trait "))?
        .strip_suffix(" not found.")
}

fn return_contract(message: &str) -> Option<(&str, &str, &str)> {
    let label = message
        .strip_prefix("Function ")
        .or_else(|| message.strip_prefix("Method "))
        .unwrap_or(message);
    let (callee, types) = label.split_once(" should return ")?;
    let (expected, given) = types
        .split_once(", but returns ")
        .or_else(|| types.split_once(" but returns "))?;
    let given = given.strip_suffix('.')?;
    let given = if given.starts_with('\'') && given.ends_with('\'') {
        "string"
    } else if given.parse::<i64>().is_ok() {
        "int"
    } else {
        given
    };
    Some((callee, expected, given))
}
