//! Write relocatable Composer PHP maps and bootstrap files.
//!
//! After `require 'vendor/autoload.php'`, PHP uses the bundled Composer ClassLoader.

use super::Maps;
use crate::{Options, Project, php};
use anyhow::Result;
use md5::{Digest, Md5};
use std::fs;
use std::path::Path;

pub(super) fn write(project: &Project, maps: &Maps, options: &Options) -> Result<()> {
    let vendor = project.vendor_dir()?;
    let composer = vendor.join("composer");
    fs::write(
        composer.join("ClassLoader.php"),
        include_bytes!("../../resources/ClassLoader.php"),
    )?;
    fs::write(
        composer.join("InstalledVersions.php"),
        include_bytes!("../../resources/InstalledVersions.php"),
    )?;
    fs::write(
        composer.join("LICENSE"),
        include_bytes!("../../resources/LICENSE.composer"),
    )?;
    for (filename, mappings) in [
        ("autoload_psr4.php", &maps.psr4),
        ("autoload_namespaces.php", &maps.psr0),
    ] {
        let mut code = php::header(&vendor, &project.directory, filename);
        code.push_str("return array(\n");
        for (prefix, paths) in mappings.iter().rev() {
            let paths = paths
                .iter()
                .map(|path| php::path(path, &vendor, &project.directory))
                .collect::<Vec<_>>()
                .join(", ");
            code.push_str(&format!("    {} => array({paths}),\n", php::quote(prefix)));
        }
        code.push_str(");\n");
        fs::write(composer.join(filename), code)?;
    }
    for (filename, mappings) in [
        (
            "autoload_classmap.php",
            maps.classes.iter().collect::<Vec<_>>(),
        ),
        (
            "autoload_files.php",
            maps.files.iter().map(|(name, path)| (name, path)).collect(),
        ),
    ] {
        let mut code = php::header(&vendor, &project.directory, filename);
        code.push_str("return array(\n");
        for (name, path) in mappings {
            code.push_str(&format!(
                "    {} => {},\n",
                php::quote(name),
                php::path(path, &vendor, &project.directory)
            ));
        }
        code.push_str(");\n");
        fs::write(composer.join(filename), code)?;
    }
    let suffix = format!(
        "{:x}",
        Md5::digest(fs::read(project.directory.join("composer.lock"))?)
    );
    let static_code = static_file(maps, &vendor, &suffix);
    fs::write(composer.join("autoload_static.php"), static_code)?;
    let authoritative = project.config_bool("classmap-authoritative");
    let real = include_str!("../../resources/autoload_real.php.in")
        .replace("@SUFFIX@", &suffix)
        .replace(
            "@AUTHORITATIVE@",
            if authoritative { "true" } else { "false" },
        );
    fs::write(composer.join("autoload_real.php"), real)?;
    let autoload = format!(
        "<?php\n\n// autoload.php @generated by Phera\n\n\
        require_once __DIR__ . '/composer/autoload_real.php';\n\n\
        return ComposerAutoloaderInit{suffix}::getLoader();\n"
    );
    fs::write(vendor.join("autoload.php"), autoload)?;
    super::platform::write(project, options)?;
    if options.verbose {
        eprintln!("Generated autoloader: {} classes.", maps.classes.len());
    }
    Ok(())
}

fn static_file(maps: &Maps, vendor: &Path, suffix: &str) -> String {
    let mut code = format!(
        "<?php\n\n// autoload_static.php @generated by Phera\n\n\
        namespace Composer\\Autoload;\n\nclass ComposerStaticInit{suffix}\n{{\n"
    );
    let path = |path: &Path| php::static_path(path, &vendor.join("composer"));
    let mut prefixes = String::new();
    let mut directories = String::new();
    let mut first_chars = std::collections::BTreeMap::<u8, Vec<(&String, usize)>>::new();
    for prefix in maps.psr4.keys().rev().filter(|prefix| !prefix.is_empty()) {
        if let Some(first) = prefix.as_bytes().first().copied() {
            first_chars
                .entry(first)
                .or_default()
                .push((prefix, prefix.len()));
        }
    }
    for (first, prefixes_for_char) in first_chars {
        prefixes.push_str(&format!("        \"\\x{first:02x}\" => array(\n"));
        for (prefix, length) in prefixes_for_char {
            prefixes.push_str(&format!(
                "            {} => {length},\n",
                php::quote(prefix)
            ));
        }
        prefixes.push_str("        ),\n");
    }
    for (prefix, paths) in maps
        .psr4
        .iter()
        .rev()
        .filter(|(prefix, _)| !prefix.is_empty())
    {
        directories.push_str(&format!(
            "        {} => array({}),\n",
            php::quote(prefix),
            paths
                .iter()
                .map(|item| path(item))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    code.push_str(&format!(
        "    public static $prefixLengthsPsr4 = array(\n{prefixes}    );\n\
        \n    public static $prefixDirsPsr4 = array(\n{directories}    );\n"
    ));
    for (property, paths) in [
        ("fallbackDirsPsr4", maps.psr4.get("")),
        ("fallbackDirsPsr0", maps.psr0.get("")),
    ] {
        let items = paths
            .into_iter()
            .flatten()
            .map(|item| path(item))
            .collect::<Vec<_>>()
            .join(", ");
        code.push_str(&format!(
            "\n    public static ${property} = array({items});\n"
        ));
    }
    let mut psr0: std::collections::BTreeMap<u8, Vec<_>> = Default::default();
    for (prefix, paths) in maps.psr0.iter().rev() {
        if let Some(first) = prefix.as_bytes().first().copied() {
            psr0.entry(first).or_default().push((prefix, paths));
        }
    }
    code.push_str("\n    public static $prefixesPsr0 = array(\n");
    for (first, items) in psr0 {
        code.push_str(&format!("        \"\\x{first:02x}\" => array(\n"));
        for (prefix, paths) in items {
            code.push_str(&format!(
                "            {} => array({}),\n",
                php::quote(prefix),
                paths
                    .iter()
                    .map(|item| path(item))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        code.push_str("        ),\n");
    }
    code.push_str("    );\n");
    for (property, entries) in [
        ("classMap", maps.classes.iter().collect::<Vec<_>>()),
        (
            "files",
            maps.files.iter().map(|(name, path)| (name, path)).collect(),
        ),
    ] {
        code.push_str(&format!("\n    public static ${property} = array(\n"));
        for (name, item) in entries {
            code.push_str(&format!(
                "        {} => {},\n",
                php::quote(name),
                path(item)
            ));
        }
        code.push_str("    );\n");
    }
    code.push_str(
        "\n    public static function getInitializer(ClassLoader $loader)\n    {\n\
        \x20       return \\Closure::bind(function () use ($loader) {\n",
    );
    for property in [
        "prefixLengthsPsr4",
        "prefixDirsPsr4",
        "fallbackDirsPsr4",
        "prefixesPsr0",
        "fallbackDirsPsr0",
        "classMap",
    ] {
        code.push_str(&format!(
            "            $loader->{property} = \
            ComposerStaticInit{suffix}::${property};\n"
        ));
    }
    code.push_str("        }, null, ClassLoader::class);\n    }\n}\n");
    code
}
