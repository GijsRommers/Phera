//! Composer-style runtime platform checks for production dependencies.
//!
//! A `"php": "^8.5"` requirement emits a PHP_VERSION_ID >= 80500 guard.

use crate::version::constraint::Operator;
use crate::{
    Lock, Options, Project, php,
    version::{Constraint, Version},
};
use anyhow::Result;
use std::collections::BTreeSet;
use std::fs;

pub(super) fn write(project: &Project, options: &Options) -> Result<()> {
    let mut code = String::from("<?php\n\n// platform_check.php @generated by Phera\n\n");
    let setting = &project.data["config"]["platform-check"];
    if options.ignore_platform || setting == false {
        fs::write(
            project.vendor_dir()?.join("composer/platform_check.php"),
            code,
        )?;
        return Ok(());
    }
    let lock = Lock::read(&project.directory)?;
    let mut requirements = vec![&project.data["require"]];
    requirements.extend(lock.packages.iter().map(|package| package.field("require")));
    let mut lowest: Option<(Version, bool)> = None;
    let mut extensions = BTreeSet::new();
    let mut bit64 = false;
    for requires in requirements {
        if let Some(requires) = requires.as_object() {
            for (name, text) in requires {
                if options.ignores_platform(name) {
                    continue;
                }
                if matches!(name.as_str(), "php" | "php-64bit") {
                    bit64 |= name == "php-64bit";
                    let constraint = Constraint::parse(text.as_str().unwrap_or("*"))?;
                    if let Some(bound) = minimum(&constraint)
                        && lowest.as_ref().is_none_or(|(version, inclusive)| {
                            bound.0 > *version || bound.0 == *version && !bound.1 && *inclusive
                        })
                    {
                        lowest = Some(bound);
                    }
                } else if let Some(extension) = name.strip_prefix("ext-") {
                    let provided = lock.packages.iter().any(|package| {
                        ["provide", "replace"]
                            .iter()
                            .any(|key| package.field(key).get(name).is_some())
                    });
                    if !provided {
                        extensions.insert(extension.replace('-', " "));
                    }
                }
            }
        }
    }
    code.push_str("$issues = array();\n");
    if let Some((version, inclusive)) = lowest {
        let numbers: Vec<u32> = version
            .normalized()
            .split(['.', '-'])
            .take(3)
            .map(|part| part.parse().unwrap_or(0))
            .collect();
        let id = numbers.first().copied().unwrap_or(0) * 10000
            + numbers.get(1).copied().unwrap_or(0) * 100
            + numbers.get(2).copied().unwrap_or(0);
        let operator = if inclusive { ">=" } else { ">" };
        code.push_str(&format!(
            "if (!(PHP_VERSION_ID {operator} {id})) {{\n\
            \x20   $issues[] = {} . PHP_VERSION . '.';\n}}\n",
            php::quote(&format!(
                "Your Composer dependencies require a PHP version \"{operator} \
                {}\". You are running ",
                version.normalized()
            ))
        ));
    }
    if bit64 {
        code.push_str(
            "if (PHP_INT_SIZE !== 8) {\n\
            \x20   $issues[] = 'Your Composer dependencies require a 64-bit build of PHP.';\n}\n",
        );
    }
    if setting == true {
        for extension in extensions {
            let name = php::quote(&extension);
            code.push_str(&format!(
                "if (!extension_loaded({name})) {{\n\
                \x20   $issues[] = {};\n}}\n",
                php::quote(&format!(
                    "Your Composer dependencies require the following PHP extension: {extension}."
                ))
            ));
        }
    }
    code.push_str(
        "if ($issues) {\n\
        \x20   throw new \\RuntimeException('Composer detected issues in your platform: ' \
        . implode(' ', $issues));\n}\n",
    );
    fs::write(
        project.vendor_dir()?.join("composer/platform_check.php"),
        code,
    )?;
    Ok(())
}

fn minimum(constraint: &Constraint) -> Option<(Version, bool)> {
    let mut bounds = Vec::new();
    for group in &constraint.groups {
        let bound = group
            .iter()
            .filter_map(|term| match term.operator {
                Operator::Equal | Operator::GreaterEqual => Some((term.version.clone(), true)),
                Operator::Greater => Some((term.version.clone(), false)),
                _ => None,
            })
            .filter(|(version, _)| !version.is_branch())
            .max_by(|left, right| left.0.cmp(&right.0).then_with(|| right.1.cmp(&left.1)));
        bounds.push(bound?);
    }
    bounds
        .into_iter()
        .min_by(|left, right| left.0.cmp(&right.0).then_with(|| right.1.cmp(&left.1)))
}
