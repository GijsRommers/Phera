//! Export PHP literals and relocatable paths, e.g. `$vendorDir . '/psr/log'`.
//!
//! Package metadata is always quoted as data and never inserted as PHP source.

use serde_json::Value;
use std::path::Path;

pub(crate) fn quote(text: &str) -> String {
    format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"))
}

pub(crate) fn value(value: &Value) -> String {
    match value {
        Value::Null => "null".into(),
        Value::Bool(value) => value.to_string(),
        Value::Number(number) => number.to_string(),
        Value::String(text) => quote(text),
        Value::Array(items) => format!(
            "array({})",
            items.iter().map(self::value).collect::<Vec<_>>().join(", ")
        ),
        Value::Object(items) => format!(
            "array({})",
            items
                .iter()
                .map(|(key, item)| { format!("{} => {}", quote(key), self::value(item)) })
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

pub(crate) fn relative(from: &Path, to: &Path) -> String {
    let from: Vec<_> = from.components().collect();
    let to: Vec<_> = to.components().collect();
    let shared = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut parts = vec!["..".to_owned(); from.len() - shared];
    parts.extend(
        to[shared..]
            .iter()
            .map(|part| part.as_os_str().to_string_lossy().into_owned()),
    );
    parts.join("/")
}

pub(crate) fn path(path: &Path, vendor: &Path, root: &Path) -> String {
    if let Ok(path) = path.strip_prefix(vendor) {
        let suffix = path.to_string_lossy();
        return format!("$vendorDir . {}", quote(&format!("/{suffix}")));
    }
    format!(
        "$baseDir . {}",
        quote(&format!("/{}", relative(root, path)))
    )
}

pub(crate) fn header(vendor: &Path, root: &Path, filename: &str) -> String {
    format!(
        "<?php\n\n// {filename} @generated by Phera\n\n\
         $vendorDir = dirname(__DIR__);\n$baseDir = $vendorDir . {};\n\n",
        quote(&format!("/{}", relative(vendor, root)))
    )
}
