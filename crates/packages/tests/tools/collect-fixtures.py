"""Collect real dist manifests and lock them with the current Composer oracle.

Example: python3 collect-fixtures.py /path/to/composer.phar
Network work belongs in this explicit maintenance tool, never the local gate.
"""
import concurrent.futures
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import urllib.request
import zipfile
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT.parents[2] / 'target' / 'package-oracle'
WORK.mkdir(parents=True, exist_ok=True)
COMPOSER = str(Path(sys.argv[1]).resolve())
PHP = os.environ.get('PHERA_PHP', '/opt/homebrew/bin/php')
NAMES = [
    'laravel/laravel', 'symfony/skeleton', 'slim/slim-skeleton', 'symfony/finder',
    'guzzlehttp/guzzle', 'psr/log', 'psr/container', 'psr/cache', 'psr/http-message',
    'psr/http-client', 'psr/http-factory', 'league/flysystem', 'league/csv',
    'league/commonmark', 'nesbot/carbon', 'ramsey/uuid', 'nikic/php-parser',
    'composer/semver', 'composer/class-map-generator', 'composer/metadata-minifier',
    'symfony/polyfill-mbstring', 'symfony/console', 'doctrine/collections',
    'webmozart/assert', 'symfony/filesystem',
]


def read(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'Phera-fixture-collector'})
    with urllib.request.urlopen(request, timeout=120) as reply:
        return reply.read()


def collect(name):
    destination = ROOT / 'fixtures' / name.replace('/', '--')
    destination.mkdir(parents=True, exist_ok=True)
    if (destination / 'composer.lock').exists():
        return name + ': already collected'
    metadata = json.loads(read('https://repo.packagist.org/p2/' + name + '.json'))
    current = {}
    chosen = None
    for delta in metadata['packages'][name]:
        for key, value in delta.items():
            if value == '__unset':
                current.pop(key, None)
            else:
                current[key] = value
        version = current['version'].lower()
        if not any(flag in version for flag in ['dev', 'alpha', 'beta', 'rc']):
            chosen = dict(current)
            break
    if chosen is None:
        raise RuntimeError('no stable version for ' + name)
    archive = zipfile.ZipFile(io.BytesIO(read(chosen['dist']['url'])))
    paths = [path for path in archive.namelist() if path.endswith('/composer.json')]
    source = min(paths, key=lambda path: path.count('/'))
    manifest = archive.read(source)
    (destination / 'composer.json').write_bytes(manifest)
    provenance = {
        'package': name, 'version': chosen['version'],
        'reference': chosen.get('source', {}).get('reference'),
        'dist': chosen['dist']['url'], 'date': datetime.now(timezone.utc).date().isoformat(),
        'lock': 'Generated by Composer 2.11.2, --ignore-platform-reqs --no-plugins --no-scripts',
        'root_version': chosen['version'],
    }
    (destination / 'provenance.json').write_text(json.dumps(provenance, indent=4) + '\n')
    environment = dict(os.environ, COMPOSER_CACHE_DIR=str(WORK / 'cache'),
                       COMPOSER_HOME=str(WORK / 'home'), COMPOSER_ROOT_VERSION=chosen['version'])
    result = subprocess.run([PHP, COMPOSER, 'update', '--no-install', '--no-interaction',
        '--no-plugins', '--no-scripts', '--ignore-platform-reqs', '--no-audit'],
        cwd=destination, env=environment, capture_output=True, text=True, timeout=300)
    (WORK / (name.replace('/', '--') + '.collect.log')).write_text(result.stdout + result.stderr)
    if result.returncode:
        raise RuntimeError(name + ': ' + result.stderr[-1200:])
    return name + ': collected ' + chosen['version']


with concurrent.futures.ThreadPoolExecutor(max_workers=6) as executor:
    for result in executor.map(collect, NAMES):
        print(result, flush=True)
